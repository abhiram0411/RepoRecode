export const getPalette = (id: ThemeId) =>
  palettes.find((p) => p.id === id) ?? palettes[0];
export function applyPalette(id: ThemeId) {
  const palette = getPalette(id);
  const root = document.documentElement;
  root.dataset.theme = id;
  root.dataset.tone = palette.light ? "light" : "dark";
  root.style.colorScheme = palette.light ? "light" : "dark";
  for (const [name, value] of Object.entries(palette.colors))
    root.style.setProperty(`--${name}`, value);
}
